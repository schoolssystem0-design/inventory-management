    USING (shop_id = app_current_shop() OR app_all_shops()) WITH CHECK (shop_id = app_current_shop() OR app_all_shops());
CREATE POLICY tenant_isolation ON app_user
    USING (shop_id = app_current_shop() OR app_all_shops()) WITH CHECK (shop_id = app_current_shop() OR app_all_shops());
CREATE POLICY tenant_isolation ON login_event
    USING (shop_id = app_current_shop() OR app_all_shops()) WITH CHECK (shop_id = app_current_shop() OR app_all_shops());
