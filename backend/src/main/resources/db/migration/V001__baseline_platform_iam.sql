-- The application connects as a LOGIN role that is a member of pos_app (created by AppDatabaseRoleCallback after
-- migrate). It owns no table, so row-level security always applies to it.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pos_app') THEN
        CREATE ROLE pos_app NOLOGIN NOSUPERUSER NOBYPASSRLS;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO pos_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO pos_app;

-- app.shop_id   : set on every connection checkout from the current TenantContext
-- app.all_shops : 'on' only inside platform cross-shop queries
CREATE FUNCTION app_current_shop() RETURNS BIGINT
    LANGUAGE sql STABLE
AS $$ SELECT NULLIF(current_setting('app.shop_id', true), '')::BIGINT $$;

CREATE FUNCTION app_all_shops() RETURNS BOOLEAN
    LANGUAGE sql STABLE
AS $$ SELECT COALESCE(current_setting('app.all_shops', true), '') = 'on' $$;

-- =====================================================================
-- Platform tables (not tenant-scoped, no RLS)
-- =====================================================================
CREATE TABLE shop_type (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    type_key         VARCHAR(40)  NOT NULL UNIQUE,
    name             VARCHAR(100) NOT NULL,
    description      VARCHAR(500) NOT NULL DEFAULT '',
    icon             VARCHAR(40)  NOT NULL DEFAULT 'store',
    default_modules  TEXT[]       NOT NULL DEFAULT '{}',
    offered_modules  TEXT[]       NOT NULL DEFAULT '{}',
    template         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    sort_order       INT          NOT NULL DEFAULT 0,
    active           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE plan (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    plan_key            VARCHAR(40)    NOT NULL UNIQUE,
    name                VARCHAR(100)   NOT NULL,
    price_month         NUMERIC(14, 2) NOT NULL,
    price_year          NUMERIC(14, 2) NOT NULL,
    setup_fee           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    max_users           INT,
    max_branches        INT,
    max_products        INT,
    max_tills           INT,
    sms_per_month       INT            NOT NULL DEFAULT 0,
    storage_mb          INT            NOT NULL DEFAULT 1024,
    phase1_modules_only BOOLEAN        NOT NULL DEFAULT FALSE,
    custom_domain       BOOLEAN        NOT NULL DEFAULT FALSE,
    sort_order          INT            NOT NULL DEFAULT 0,
    active              BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE TABLE platform_user (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email            VARCHAR(254) NOT NULL,
    name             VARCHAR(200) NOT NULL,
    role             VARCHAR(20)  NOT NULL DEFAULT 'SUPER_ADMIN'
                     CHECK (role IN ('SUPER_ADMIN', 'SUPPORT', 'BILLING', 'ONBOARDING')),
    password_hash    VARCHAR(200) NOT NULL,
    totp_secret      VARCHAR(200),
    status           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    failed_attempts  INT          NOT NULL DEFAULT 0,
    locked_until     TIMESTAMPTZ,
    last_login_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX platform_user_email_uq ON platform_user (lower(email));

CREATE TABLE platform_login_event (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    platform_user_id  BIGINT       REFERENCES platform_user (id),
    email             VARCHAR(254) NOT NULL,
    result            VARCHAR(20)  NOT NULL,
    ip                VARCHAR(64),
    user_agent        VARCHAR(400),
    at                TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX platform_login_event_at_idx ON platform_login_event (at DESC);

CREATE TABLE shop (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(30)  NOT NULL,
    name            VARCHAR(200) NOT NULL,
    shop_type_id    BIGINT       NOT NULL REFERENCES shop_type (id),
    plan_id         BIGINT       NOT NULL REFERENCES plan (id),
    status          VARCHAR(20)  NOT NULL DEFAULT 'TRIAL'
                    CHECK (status IN ('TRIAL', 'ACTIVE', 'GRACE', 'READ_ONLY', 'SUSPENDED', 'CLOSED')),
    status_reason   VARCHAR(500),
    owner_name      VARCHAR(200) NOT NULL,
    phone           VARCHAR(30),
    email           VARCHAR(254),
    city            VARCHAR(100),
    address         VARCHAR(500),
    ntn             VARCHAR(30),
    timezone        VARCHAR(64)  NOT NULL DEFAULT 'Asia/Karachi',
    notes           TEXT,
    trial_ends_on   DATE,
    closed_at       TIMESTAMPTZ,
    delete_after    DATE,
    created_by      BIGINT       REFERENCES platform_user (id),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT shop_code_format CHECK (code ~ '^[a-z0-9]([a-z0-9-]{0,28}[a-z0-9])?$' AND length(code) >= 2)
);
CREATE UNIQUE INDEX shop_code_uq ON shop (code);
CREATE INDEX shop_status_idx ON shop (status);

CREATE TABLE shop_domain (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shop_id      BIGINT       NOT NULL REFERENCES shop (id) ON DELETE CASCADE,
    host         VARCHAR(253) NOT NULL,
    verified     BOOLEAN      NOT NULL DEFAULT FALSE,
    is_primary   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX shop_domain_host_uq ON shop_domain (lower(host));

-- Effective module switches per shop (docs/SHOP-TYPES-AND-MODULES.md §1). Readable by the shop's users.
CREATE TABLE shop_module (
    shop_id      BIGINT      NOT NULL REFERENCES shop (id) ON DELETE CASCADE,
    module_key   VARCHAR(40) NOT NULL,
    enabled      BOOLEAN     NOT NULL,
    source       VARCHAR(20) NOT NULL CHECK (source IN ('TYPE', 'PLAN', 'OVERRIDE')),
    changed_by   BIGINT      REFERENCES platform_user (id),
    changed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (shop_id, module_key)
);

CREATE TABLE subscription (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shop_id       BIGINT         NOT NULL UNIQUE REFERENCES shop (id) ON DELETE CASCADE,
    plan_id       BIGINT         NOT NULL REFERENCES plan (id),
    cycle         VARCHAR(10)    NOT NULL CHECK (cycle IN ('MONTH', 'YEAR')),
    price         NUMERIC(14, 2) NOT NULL,
    discount      NUMERIC(14, 2) NOT NULL DEFAULT 0,
    setup_fee     NUMERIC(14, 2) NOT NULL DEFAULT 0,
    starts_on     DATE           NOT NULL,
    next_due_on   DATE           NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE TABLE support_session (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    platform_user_id  BIGINT       NOT NULL REFERENCES platform_user (id),
    shop_id           BIGINT       NOT NULL REFERENCES shop (id) ON DELETE CASCADE,
    reason            VARCHAR(500) NOT NULL,
    write_approved_at TIMESTAMPTZ,
    started_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ended_at          TIMESTAMPTZ
);

CREATE TABLE platform_setting (
    setting_key  VARCHAR(60)  PRIMARY KEY,
    value        VARCHAR(500) NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE platform_audit_log (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT       REFERENCES platform_user (id),
    action      VARCHAR(60)  NOT NULL,
    shop_id     BIGINT       REFERENCES shop (id) ON DELETE SET NULL,
    details     JSONB,
    ip          VARCHAR(64),
    at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX platform_audit_log_at_idx ON platform_audit_log (at DESC);

-- Gap-free per-shop counters (SKUs, document numbers). Tenant table.
CREATE TABLE number_sequence (
    shop_id     BIGINT      NOT NULL REFERENCES shop (id),
    name        VARCHAR(60) NOT NULL,
    next_value  BIGINT      NOT NULL DEFAULT 1,
    PRIMARY KEY (shop_id, name)
);

-- =====================================================================
-- Shop users and access (tenant tables)
-- =====================================================================
CREATE TABLE role (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shop_id      BIGINT       NOT NULL REFERENCES shop (id),
    name         VARCHAR(100) NOT NULL,
    system_key   VARCHAR(40),
    description  VARCHAR(300) NOT NULL DEFAULT '',
    permissions  TEXT[]       NOT NULL DEFAULT '{}',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT role_shop_id_uq UNIQUE (shop_id, id)
);
CREATE UNIQUE INDEX role_name_uq ON role (shop_id, lower(name));
CREATE UNIQUE INDEX role_system_key_uq ON role (shop_id, system_key) WHERE system_key IS NOT NULL;

CREATE TABLE app_user (
    id                    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shop_id               BIGINT       NOT NULL REFERENCES shop (id),
    username              VARCHAR(60)  NOT NULL,
    display_name          VARCHAR(200) NOT NULL,
    phone                 VARCHAR(30),
    email                 VARCHAR(254),
    role_id               BIGINT       NOT NULL,
    is_owner              BOOLEAN      NOT NULL DEFAULT FALSE,
    all_branches          BOOLEAN      NOT NULL DEFAULT TRUE,
    password_hash         VARCHAR(200) NOT NULL,
    must_change_password  BOOLEAN      NOT NULL DEFAULT FALSE,
    pin_hash              VARCHAR(200),
    pin_failed_attempts   INT          NOT NULL DEFAULT 0,
    pin_locked_until      TIMESTAMPTZ,
    totp_secret           VARCHAR(200),
    status                VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    failed_attempts       INT          NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    last_login_at         TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT app_user_shop_id_uq UNIQUE (shop_id, id),
    CONSTRAINT app_user_role_fk FOREIGN KEY (shop_id, role_id) REFERENCES role (shop_id, id)
);
CREATE UNIQUE INDEX app_user_username_uq ON app_user (shop_id, lower(username));
CREATE UNIQUE INDEX app_user_one_owner_uq ON app_user (shop_id) WHERE is_owner;

CREATE TABLE login_event (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shop_id      BIGINT       NOT NULL REFERENCES shop (id),
    user_id      BIGINT,
    username     VARCHAR(60)  NOT NULL,
    result       VARCHAR(20)  NOT NULL CHECK (result IN ('SUCCESS', 'INVALID', 'BLOCKED', 'TOTP_INVALID')),
    ip           VARCHAR(64),
    user_agent   VARCHAR(400),
    at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT login_event_user_fk FOREIGN KEY (shop_id, user_id) REFERENCES app_user (shop_id, id)
);
CREATE INDEX login_event_shop_at_idx ON login_event (shop_id, at DESC);

CREATE TABLE audit_log (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shop_id             BIGINT       NOT NULL REFERENCES shop (id),
    actor_type          VARCHAR(20)  NOT NULL CHECK (actor_type IN ('USER', 'PLATFORM', 'SYSTEM')),
    actor_id            BIGINT,
    actor_name          VARCHAR(200),
    support_session_id  BIGINT,
    action              VARCHAR(60)  NOT NULL,
    entity_type         VARCHAR(60),
    entity_id           BIGINT,
    before_data         JSONB,
    after_data          JSONB,
    reason              VARCHAR(500),
    ip                  VARCHAR(64),
    at                  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_shop_at_idx ON audit_log (shop_id, at DESC);
CREATE INDEX audit_log_entity_idx ON audit_log (shop_id, entity_type, entity_id);

CREATE TABLE password_token (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shop_id          BIGINT       NOT NULL REFERENCES shop (id),
    user_id          BIGINT       NOT NULL,
    purpose          VARCHAR(10)  NOT NULL CHECK (purpose IN ('SETUP', 'RESET')),
    token_hash       VARCHAR(64)  NOT NULL,
    expires_at       TIMESTAMPTZ  NOT NULL,
    used_at          TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT password_token_user_fk FOREIGN KEY (shop_id, user_id) REFERENCES app_user (shop_id, id)
);
CREATE UNIQUE INDEX password_token_hash_uq ON password_token (token_hash);

ALTER TABLE number_sequence ENABLE ROW LEVEL SECURITY;
